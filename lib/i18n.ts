const DICTIONARIES: Record<Locale, Dictionary> = {
  ko,
  en,
  ja,
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  es,
  fr,
  de,
};

const STORAGE_KEY = "badgeflow-locale-v1";

function resolveLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  const exact = SUPPORTED_LOCALES.find(({ code }) => code === value);
  if (exact) return exact.code;
  const normalized = value.toLowerCase();
  if (normalized.startsWith("zh-tw") || normalized.startsWith("zh-hk")) {
    return "zh-TW";
  }
  if (normalized.startsWith("zh")) return "zh-CN";
  return (
    SUPPORTED_LOCALES.find(({ code }) =>
      normalized.startsWith(code.toLowerCase()),
    )?.code ?? null
  );
}

export type Translate = (
  key: MessageKey,
  values?: Record<string, string | number>,
) => string;

export function useI18n() {
  const [locale, setLocaleState] = useState<Locale>("ko");

  useEffect(() => {
    let saved: string | null = null;
    try {
      saved = localStorage.getItem(STORAGE_KEY);
    } catch {
      // Browser privacy settings can disable localStorage.
    }
    const detected =
      resolveLocale(saved) ??
      navigator.languages.map(resolveLocale).find(Boolean) ??
      "ko";
    setLocaleState(detected);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // Language selection still works for the current session.
    }
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
  }, []);

  const t = useCallback<Translate>(
    (key, values) => {
      let message = DICTIONARIES[locale][key] ?? en[key];
      if (values) {
        Object.entries(values).forEach(([name, value]) => {
          message = message.replaceAll(`{${name}}`, String(value));
        });
      }
      return message;
    },
    [locale],
  );

  return { locale, setLocale, t };
}
